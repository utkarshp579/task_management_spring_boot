package org.example.taskmanagement2.entity;

import jakarta.persistence.*;

@Entity
public class Task {
    @Id
    @GeneratedValue(strategy= GenerationType.IDENTITY)
    int id ;

    @Column(length = 100 , nullable = false)
    String description;

    @Column
    String status = "pending";

    // no arg constructor is default connected.

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public int getId() {
        return id;
    }

//    public void setId(int id) {  // Keeping it safe from external unwanted updates. as Id is generated by Database automatically.
//        this.id = id;
//    }

}
